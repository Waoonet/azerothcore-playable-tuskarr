#!/usr/bin/env bash
set -euo pipefail

CORE_ROOT="${CORE_ROOT:-/home/azeroth/azerothcore}"
SERVER_ROOT="${SERVER_ROOT:-/home/azeroth/server}"
FRESH_OUT="${1:-}"
JOBS="${JOBS:-16}"
EXPECTED_CORE="413bea61a85e20d9caef7d66fc601a661fdddd9d"
LIVE_CONF_DIR="$SERVER_ROOT/etc"

fail() { echo "ERROR: $*" >&2; exit 1; }
[[ $EUID -eq 0 ]] || fail "run as root"
[[ -n "$FRESH_OUT" && -d "$FRESH_OUT" ]] || fail "usage: $0 /root/tuskarr-fresh-build-YYYYMMDD-HHMMSS"
[[ -d "$CORE_ROOT/.git" ]] || fail "AzerothCore source tree missing: $CORE_ROOT"

META="$FRESH_OUT/BUILD-METADATA.env"
BUILD_DIR="$FRESH_OUT/build"
STAGE_DIR="$FRESH_OUT/stage"
ARTIFACT_DIR="$FRESH_OUT/artifact"
LOG_DIR="$FRESH_OUT/logs"
REPORT="$FRESH_OUT/CONF-DIR-REBUILD-REPORT.txt"
[[ -f "$META" ]] || fail "build metadata missing: $META"
[[ -f "$BUILD_DIR/CMakeCache.txt" ]] || fail "fresh CMake cache missing"
mkdir -p "$ARTIFACT_DIR" "$LOG_DIR"

# Generated by our own staging tools under /root; safe to source after existence checks.
# shellcheck disable=SC1090
source "$META"
[[ "${CORE_ROOT:-}" == "/home/azeroth/azerothcore" ]] || fail "metadata core root mismatch"
[[ "${CORE_HEAD:-}" == "$EXPECTED_CORE" ]] || fail "metadata core revision mismatch"
[[ -n "${BUNDLE:-}" && -d "$BUNDLE" ]] || fail "metadata bundle missing: ${BUNDLE:-unset}"
PATCH="$BUNDLE/server/core/playerbots-exclude-tuskarr-random-generation.patch"
[[ -f "$PATCH" ]] || fail "playerbots safeguard patch missing"

HEAD="$(git -C "$CORE_ROOT" rev-parse HEAD)"
[[ "$HEAD" == "$EXPECTED_CORE" ]] || fail "unexpected AzerothCore revision: $HEAD"
[[ -z "$(git -C "$CORE_ROOT" status --porcelain)" ]] || fail "AzerothCore working tree is not clean"
git -C "$CORE_ROOT" apply --check "$PATCH"

exec > >(tee "$REPORT") 2>&1

echo "===== Repair verified fresh worldserver config directory ====="
echo "Fresh output:    $FRESH_OUT"
echo "Build tree:      $BUILD_DIR"
echo "Stage prefix:    $STAGE_DIR"
echo "Live config dir: $LIVE_CONF_DIR"
echo "Core HEAD:       $HEAD"
echo "Jobs:            $JOBS"
echo "Mode:            BUILD/STAGE ONLY - LIVE REALM IS NOT MODIFIED"

TARGET_CPP="$CORE_ROOT/modules/mod-playerbots/src/Bot/Factory/RandomPlayerbotFactory.cpp"
ORIGINAL_CPP="$FRESH_OUT/RandomPlayerbotFactory.cpp.confdir-repair-original"
cp -a "$TARGET_CPP" "$ORIGINAL_CPP"
PATCH_APPLIED=0
restore_source() {
    if (( PATCH_APPLIED == 1 )); then
        cp -a "$ORIGINAL_CPP" "$TARGET_CPP"
        PATCH_APPLIED=0
    fi
}
on_exit() {
    local rc=$?
    restore_source
    if [[ -n "$(git -C "$CORE_ROOT" status --porcelain 2>/dev/null || true)" ]]; then
        echo "WARNING: source tree is not clean after repair attempt" >&2
        git -C "$CORE_ROOT" status --short >&2 || true
    fi
    exit "$rc"
}
trap on_exit EXIT

echo
echo "===== Current MySQL gate ====="
command -v mysql_config >/dev/null || fail "mysql_config not found"
command -v g++ >/dev/null || fail "g++ not found"
PROBE_CPP="$FRESH_OUT/mysql-version-probe-confdir.cpp"
PROBE_BIN="$FRESH_OUT/mysql-version-probe-confdir"
cat > "$PROBE_CPP" <<'CPP'
#include <mysql.h>
#include <iostream>
int main()
{
    std::cout << MYSQL_VERSION_ID << " " << mysql_get_client_version() << " " << mysql_get_client_info() << "\n";
    return MYSQL_VERSION_ID == mysql_get_client_version() ? 0 : 2;
}
CPP
# shellcheck disable=SC2046
g++ $(mysql_config --cflags) "$PROBE_CPP" -o "$PROBE_BIN" $(mysql_config --libs)
PROBE_LINE="$("$PROBE_BIN")" || fail "current MySQL headers/runtime mismatch"
read -r MYSQL_COMPILE_ID MYSQL_RUNTIME_ID MYSQL_INFO <<<"$PROBE_LINE"
echo "compile=$MYSQL_COMPILE_ID runtime=$MYSQL_RUNTIME_ID info=$MYSQL_INFO"
[[ "$MYSQL_COMPILE_ID" == "$MYSQL_RUNTIME_ID" ]] || fail "MySQL compile/runtime mismatch"
[[ "$MYSQL_COMPILE_ID" == "80411" ]] || fail "expected audited MySQL 80411, got $MYSQL_COMPILE_ID"
echo "PASS: MySQL build environment remains 80411"

echo
echo "===== Apply playerbots safeguard temporarily ====="
git -C "$CORE_ROOT" apply "$PATCH"
PATCH_APPLIED=1
git -C "$CORE_ROOT" apply -R --check "$PATCH"
echo "PASS: playerbots safeguard applied temporarily"

echo
echo "===== Reconfigure existing fresh tree with explicit live CONF_DIR ====="
cmake -S "$CORE_ROOT" -B "$BUILD_DIR" \
    -G "Unix Makefiles" \
    -DCMAKE_BUILD_TYPE=RelWithDebInfo \
    -DCMAKE_INSTALL_PREFIX="$STAGE_DIR" \
    -DCONF_DIR:PATH="$LIVE_CONF_DIR" \
    2>&1 | tee "$LOG_DIR/cmake-configure-confdir.log"

CACHE="$BUILD_DIR/CMakeCache.txt"
HOME_DIR="$(sed -n 's/^CMAKE_HOME_DIRECTORY:INTERNAL=//p' "$CACHE" | tail -n1)"
PREFIX="$(sed -n 's/^CMAKE_INSTALL_PREFIX:PATH=//p' "$CACHE" | tail -n1)"
CONF_CACHE="$(sed -n 's/^CONF_DIR:PATH=//p' "$CACHE" | tail -n1)"
[[ "$HOME_DIR" == "$CORE_ROOT" ]] || fail "CMake source changed unexpectedly: $HOME_DIR"
[[ "$PREFIX" == "$STAGE_DIR" ]] || fail "CMake stage prefix changed unexpectedly: $PREFIX"
[[ "$CONF_CACHE" == "$LIVE_CONF_DIR" ]] || fail "CONF_DIR cache mismatch: $CONF_CACHE"
echo "PASS: CMAKE_HOME_DIRECTORY=$HOME_DIR"
echo "PASS: CMAKE_INSTALL_PREFIX=$PREFIX"
echo "PASS: CONF_DIR=$CONF_CACHE"

COMPILE_DB="$BUILD_DIR/compile_commands.json"
[[ -f "$COMPILE_DB" ]] || fail "compile_commands.json missing"
if grep -Fq "/home/azeroth/update-work-20260910-145140/azerothcore" "$CACHE" "$COMPILE_DB"; then
    fail "build tree references obsolete September 10 source"
fi
if grep -Fq "$STAGE_DIR/etc" "$COMPILE_DB"; then
    fail "compile database still contains staging config directory"
fi
grep -F '_CONF_DIR' "$COMPILE_DB" | grep -Fq "$LIVE_CONF_DIR" || fail "compile database does not carry live _CONF_DIR definition"
echo "PASS: compile database uses live _CONF_DIR and active source only"

echo
echo "===== Rebuild worldserver after CONF_DIR change ====="
set +e
cmake --build "$BUILD_DIR" --target worldserver -- -j"$JOBS" 2>&1 | tee "$LOG_DIR/build-worldserver-confdir.log"
BUILD_RC=${PIPESTATUS[0]}
set -e
[[ "$BUILD_RC" -eq 0 ]] || fail "worldserver rebuild failed"

NEW_BIN="$BUILD_DIR/src/server/apps/worldserver"
[[ -x "$NEW_BIN" ]] || fail "rebuilt worldserver missing: $NEW_BIN"

echo
echo "===== Restore source before artifact audit ====="
restore_source
[[ -z "$(git -C "$CORE_ROOT" status --porcelain)" ]] || fail "source tree did not return clean"
echo "PASS: AzerothCore source tree restored clean"

echo
echo "===== Rebuilt binary config-path audit ====="
stat -c 'owner=%U:%G mode=%a size=%s mtime=%y' "$NEW_BIN"
NEW_SHA="$(sha256sum "$NEW_BIN" | awk '{print $1}')"
echo "$NEW_SHA  $NEW_BIN"
ldd "$NEW_BIN" | grep -E 'mysql|mariadb' || fail "worldserver is not linked to MySQL client library"
strings "$NEW_BIN" | grep -Fq "$LIVE_CONF_DIR" || fail "rebuilt binary does not embed live config directory"
if strings "$NEW_BIN" | grep -Fq "$STAGE_DIR/etc"; then
    fail "rebuilt binary still embeds staging config directory"
fi
if strings "$NEW_BIN" | grep -Fq "/home/azeroth/update-work-20260910-145140/azerothcore"; then
    fail "rebuilt binary embeds obsolete September 10 source path"
fi
echo "PASS: binary embeds live config directory and no obsolete/staging config path"

install -m 0755 "$NEW_BIN" "$ARTIFACT_DIR/worldserver"
ART_SHA="$(sha256sum "$ARTIFACT_DIR/worldserver" | awk '{print $1}')"
[[ "$ART_SHA" == "$NEW_SHA" ]] || fail "artifact checksum differs after promotion"
printf '%s  %s\n' "$ART_SHA" "$ARTIFACT_DIR/worldserver" > "$ARTIFACT_DIR/worldserver.sha256"

cat > "$META" <<EOF
CORE_ROOT=/home/azeroth/azerothcore
CORE_HEAD=$HEAD
BUILD_DIR=$BUILD_DIR
BUNDLE=$BUNDLE
MYSQL_VERSION_ID=$MYSQL_COMPILE_ID
CONF_DIR=$LIVE_CONF_DIR
WORLD_SERVER=$ARTIFACT_DIR/worldserver
WORLD_SERVER_SHA256=$ART_SHA
PROVENANCE_GATE=cmake+compile_commands+mysql+live-confdir-v3
EOF

echo
echo "===== Config-directory repair result ====="
echo "SOURCE_PATH_MATCH=YES"
echo "MYSQL_BUILD_ENV_MATCH=YES"
echo "FRESH_CMAKE_HOME_MATCH=YES"
echo "LIVE_CONF_DIR_MATCH=YES"
echo "STAGING_CONF_DIR_IN_BINARY=NO"
echo "OBSOLETE_SOURCE_PATH_IN_BINARY=NO"
echo "SOURCE_TREE_CLEAN=YES"
echo "RESULT: PASS"
echo "Artifact: $ARTIFACT_DIR/worldserver"
echo "Artifact SHA256: $ART_SHA"
echo "Metadata: $META"
echo "Report: $REPORT"
echo "No live server, database, DBC, MPQ, configuration, or installed binary was modified."

trap - EXIT
